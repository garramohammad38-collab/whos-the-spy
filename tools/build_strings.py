#!/usr/bin/env python3
"""Generate <lang>.lproj/Localizable.strings and InfoPlist.strings from tools/strings_source.py
and check that every key used in Swift exists in both languages."""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from strings_source import S, INFO

COLUMN = {"ar": 0, "en": 1}
def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"')

for lang, i in COLUMN.items():
    d = ROOT / "SpyGame" / "Resources" / f"{lang}.lproj"
    d.mkdir(parents=True, exist_ok=True)
    (d / "Localizable.strings").write_text(
        "/* Generated by tools/build_strings.py */\n" +
        "".join(f'"{k}" = "{esc(v[i])}";\n' for k, v in S.items()), encoding="utf-8")
    (d / "InfoPlist.strings").write_text(
        "".join(f'"{k}" = "{esc(v[i])}";\n' for k, v in INFO.items()), encoding="utf-8")

src = "\n".join(p.read_text(encoding="utf-8") for p in (ROOT / "SpyGame").rglob("*.swift"))
used = set(re.findall(r'\bt\(\s*"([a-zA-Z0-9_.]+)"', src))
decks = re.search(r"case stars, mix.*?\n(.*?)\n", src, re.S)
cats = ["stars","mix","legends","arab","places","games","people",
        "animals","countries","food","jobs","things","arabcelebs","movies","cartoons"]
used |= {f"category.{c}.title" for c in cats} | {"section.football", "section.party", "category.count", "category.countCards"}
used |= {f"store.{k}.{x}" for k in ("weekly", "monthly") for x in ("title", "period")}
used |= {"store.benefit.decks", "store.benefit.words", "store.benefit.instant", "store.unavailable", "store.failed"}
used |= {f"howto.step{i}" for i in range(1, 6)}
missing = sorted(used - set(S))
bad_fmt = [k for k, v in S.items() if re.findall(r"%[@d]", v[0]) != re.findall(r"%[@d]", v[1])]
empty = [k for k, v in S.items() if not v[0] or not v[1]]
print(f"{len(S)} keys x 2 languages written")
if missing: print("MISSING KEYS:", missing)
if bad_fmt: print("FORMAT MISMATCH:", bad_fmt)
if empty: print("EMPTY:", empty)
sys.exit(1 if missing or bad_fmt or empty else 0)
